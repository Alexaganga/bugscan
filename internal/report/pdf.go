package report

import (
	"fmt"
	"strings"
	"time"

	"github.com/go-pdf/fpdf"

	"bugscan/internal/check"
)

func sevColor(s check.Severity) (int, int, int) {
	switch s {
	case check.High:
		return 192, 38, 38
	case check.Medium:
		return 217, 119, 6
	case check.Low:
		return 161, 98, 7
	}
	return 71, 85, 105
}

func gradeColor(g string) (int, int, int) {
	switch g {
	case "A", "B":
		return 22, 163, 74
	case "C":
		return 202, 138, 4
	}
	return 192, 38, 38
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// PDF writes a downloadable report: summary, prioritised action plan, details.
func PDF(path string, m Meta, findings []check.Finding, errs []error) error {
	sortFindings(findings)
	plan := BuildPlan(findings)
	score, grade := Score(findings)
	counts := Counts(findings)

	pdf := fpdf.New("P", "mm", "A4", "")
	tr := pdf.UnicodeTranslatorFromDescriptor("") // core fonts only support Latin-1
	pdf.SetTitle(tr("Security Scan Report - "+m.Target), false)
	pdf.SetAuthor("bugscan", false)
	pdf.SetMargins(15, 15, 15)
	pdf.SetAutoPageBreak(true, 18)
	pdf.AliasNbPages("")
	pdf.SetFooterFunc(func() {
		pdf.SetY(-12)
		pdf.SetFont("Helvetica", "I", 8)
		pdf.SetTextColor(120, 120, 120)
		pdf.CellFormat(0, 8, fmt.Sprintf("bugscan report - page %d of {nb}", pdf.PageNo()), "", 0, "C", false, 0, "")
	})
	pdf.AddPage()

	h2 := func(s string) {
		pdf.Ln(4)
		pdf.SetFont("Helvetica", "B", 13)
		pdf.SetTextColor(20, 30, 60)
		pdf.CellFormat(0, 8, tr(s), "B", 1, "L", false, 0, "")
		pdf.Ln(3)
	}
	kv := func(w float64, k, v string) {
		if v == "" {
			return
		}
		pdf.SetFont("Helvetica", "B", 9)
		pdf.SetTextColor(70, 70, 70)
		pdf.CellFormat(w, 5, tr(k), "", 0, "L", false, 0, "")
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(30, 30, 30)
		pdf.MultiCell(0, 5, tr(v), "", "L", false)
	}
	ensure := func(h float64) {
		if pdf.GetY()+h > 275 {
			pdf.AddPage()
		}
	}

	// title band
	pdf.SetFillColor(20, 30, 60)
	pdf.Rect(0, 0, 210, 34, "F")
	pdf.SetXY(15, 9)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont("Helvetica", "B", 22)
	pdf.CellFormat(0, 10, "Security Scan Report", "", 1, "L", false, 0, "")
	pdf.SetX(15)
	pdf.SetFont("Helvetica", "", 10)
	pdf.CellFormat(0, 6, "Generated by bugscan - passive web security checks", "", 1, "L", false, 0, "")
	pdf.SetY(42)

	kv(28, "Target", m.Target)
	kv(28, "Scanned", m.Started.Format("2006-01-02 15:04 MST"))
	kv(28, "Duration", m.Duration.Round(time.Millisecond).String())
	kv(28, "Checks run", strings.Join(m.ChecksRun, ", "))

	// summary
	h2("Summary")
	y := pdf.GetY()
	gr, gg, gb := gradeColor(grade)
	pdf.SetFillColor(gr, gg, gb)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetFont("Helvetica", "B", 36)
	pdf.CellFormat(28, 28, grade, "", 0, "C", true, 0, "")
	pdf.SetXY(48, y+3)
	pdf.SetTextColor(20, 30, 60)
	pdf.SetFont("Helvetica", "B", 14)
	pdf.CellFormat(0, 7, fmt.Sprintf("Score: %d / 100", score), "", 1, "L", false, 0, "")
	pdf.SetX(48)
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(70, 70, 70)
	verdict := "No issues were found by the checks that ran."
	if n := len(findings); n > 0 {
		verdict = fmt.Sprintf("%d issue(s) found, covered by %d recommended fix(es). Start with the action plan below, highest priority first.", n, len(plan))
	}
	pdf.MultiCell(0, 5, tr(verdict), "", "L", false)
	pdf.SetY(y + 33)

	for _, s := range []check.Severity{check.High, check.Medium, check.Low, check.Info} {
		r, g, b := sevColor(s)
		pdf.SetFillColor(r, g, b)
		pdf.SetTextColor(255, 255, 255)
		pdf.SetFont("Helvetica", "B", 11)
		pdf.CellFormat(43, 12, fmt.Sprintf("%d %s", counts[s], titleCase(string(s))), "", 0, "C", true, 0, "")
		pdf.CellFormat(2.67, 12, "", "", 0, "C", false, 0, "")
	}
	pdf.Ln(16)

	// action plan
	h2("What to fix first")
	if len(plan) == 0 {
		pdf.SetFont("Helvetica", "", 10)
		pdf.SetTextColor(30, 30, 30)
		pdf.MultiCell(0, 5, tr("Nothing to fix based on the checks that ran."), "", "L", false)
	}
	for i, a := range plan {
		ensure(28)
		pdf.SetFont("Helvetica", "B", 10)
		pdf.SetTextColor(20, 30, 60)
		pdf.CellFormat(8, 6, fmt.Sprintf("%d.", i+1), "", 0, "L", false, 0, "")
		r, g, b := sevColor(a.Severity)
		pdf.SetFillColor(r, g, b)
		pdf.SetTextColor(255, 255, 255)
		pdf.SetFont("Helvetica", "B", 8)
		pdf.CellFormat(32, 6, a.Priority, "", 1, "C", true, 0, "")
		pdf.SetX(23)
		pdf.SetFont("Helvetica", "B", 10)
		pdf.SetTextColor(30, 30, 30)
		pdf.MultiCell(0, 5, tr(a.Fix), "", "L", false)
		pdf.SetX(23)
		pdf.SetFont("Helvetica", "I", 9)
		pdf.SetTextColor(100, 100, 100)
		pdf.MultiCell(0, 5, tr("Resolves: "+strings.Join(a.Issues, "; ")), "", "L", false)
		pdf.Ln(3)
	}

	// detailed findings
	if len(findings) > 0 {
		h2("Detailed findings")
	}
	for i, f := range findings {
		ensure(36)
		r, g, b := sevColor(f.Severity)
		pdf.SetFillColor(r, g, b)
		pdf.SetTextColor(255, 255, 255)
		pdf.SetFont("Helvetica", "B", 8)
		pdf.CellFormat(20, 6, strings.ToUpper(string(f.Severity)), "", 0, "C", true, 0, "")
		pdf.SetTextColor(20, 30, 60)
		pdf.SetFont("Helvetica", "B", 10)
		pdf.CellFormat(0, 6, tr(fmt.Sprintf("  %d. %s", i+1, f.Title)), "", 1, "L", false, 0, "")
		kv(24, "Check", f.CheckID)
		kv(24, "Target", f.Target)
		kv(24, "Evidence", f.Evidence)
		kv(24, "How to fix", f.Remediation)
		pdf.Ln(3)
	}

	// checks that failed to run
	if len(errs) > 0 {
		h2("Checks that could not complete")
		for _, e := range errs {
			pdf.SetFont("Helvetica", "", 9)
			pdf.SetTextColor(30, 30, 30)
			pdf.MultiCell(0, 5, tr("- "+e.Error()), "", "L", false)
		}
	}

	// scope note
	ensure(30)
	h2("About this report")
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(70, 70, 70)
	pdf.MultiCell(0, 5, tr("This is an automated, passive scan. It checks a limited set of common issues and is not a full penetration test. "+
		"A clean result does not prove a system is secure, and the score is a simple heuristic based only on the checks that ran. "+
		"Only scan systems you own or have written permission to test."), "", "L", false)

	return pdf.OutputFileAndClose(path)
}
